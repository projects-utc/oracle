-- ============================================================================
-- Sephora Oracle Backend - V1 Schema Definition
-- Dialect: Oracle 19c / 21c / 23ai Compatible
-- All tables are prefixed with 'sep_' to ensure isolation in shared schemas.
-- ============================================================================

-- 1. USERS
CREATE TABLE sep_users (
    id                 NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    username           VARCHAR2(50) NOT NULL UNIQUE,
    password_hash      VARCHAR2(255) NOT NULL,
    full_name          VARCHAR2(100) NOT NULL,
    email              VARCHAR2(100) UNIQUE,
    phone              VARCHAR2(20),
    user_role          VARCHAR2(20) DEFAULT 'CUSTOMER' NOT NULL,
    account_status     VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    loyalty_tier       VARCHAR2(20) DEFAULT 'INSIDER' NOT NULL,
    points_balance     NUMBER(10,0) DEFAULT 0 NOT NULL,
    preferred_store_id NUMBER(19,0),
    created_at         TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at         TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. CATEGORIES
CREATE TABLE sep_categories (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    category_code VARCHAR2(50) NOT NULL UNIQUE,
    slug          VARCHAR2(100) NOT NULL UNIQUE,
    label         VARCHAR2(100) NOT NULL,
    has_sparkle   NUMBER(10,0) DEFAULT 0 NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL
);

-- 3. SUBCATEGORIES
CREATE TABLE sep_subcategories (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    category_id   NUMBER(19,0) NOT NULL,
    label         VARCHAR2(100) NOT NULL,
    slug          VARCHAR2(100) NOT NULL,
    href          VARCHAR2(255) NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_sep_subcat_cat FOREIGN KEY (category_id) REFERENCES sep_categories(id) ON DELETE CASCADE
);

-- 4. PRODUCTS (ProductCode not unique because P449116 / P502185 have multiple SKUs; sku_id is unique)
CREATE TABLE sep_products (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    product_code  VARCHAR2(50) NOT NULL,
    sku_id        VARCHAR2(50) NOT NULL UNIQUE,
    brand         VARCHAR2(150) NOT NULL,
    name          VARCHAR2(255) NOT NULL,
    category_slug VARCHAR2(100) NOT NULL,
    price_display VARCHAR2(50) NOT NULL,
    price_value   NUMBER(12,2) NOT NULL,
    variation     VARCHAR2(150),
    rating_value  NUMBER(3,2) DEFAULT 0.00 NOT NULL,
    reviews_count NUMBER(10,0) DEFAULT 0 NOT NULL,
    image_url     VARCHAR2(500) NOT NULL,
    badge         VARCHAR2(100),
    product_url   VARCHAR2(500) NOT NULL,
    stock_qty     NUMBER(10,0) DEFAULT 50 NOT NULL,
    is_active     NUMBER(10,0) DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at    TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_sep_prod_cat ON sep_products(category_slug);
CREATE INDEX idx_sep_prod_brand ON sep_products(brand);

-- 5. PRODUCT COLLECTIONS MAPPING
CREATE TABLE sep_product_collections (
    id              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    collection_code VARCHAR2(50) NOT NULL,
    product_id      NUMBER(19,0) NOT NULL,
    display_order   NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT uk_sep_prod_col UNIQUE (collection_code, product_id),
    CONSTRAINT fk_sep_col_prod FOREIGN KEY (product_id) REFERENCES sep_products(id) ON DELETE CASCADE
);

CREATE INDEX idx_sep_col_code ON sep_product_collections(collection_code, display_order);

-- 6. HERO BANNERS
CREATE TABLE sep_hero_banners (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    banner_code   VARCHAR2(150) NOT NULL UNIQUE,
    bg_color      VARCHAR2(30) NOT NULL,
    text_color    VARCHAR2(30) NOT NULL,
    image_url     VARCHAR2(500) NOT NULL,
    alt_text      VARCHAR2(500),
    title         VARCHAR2(255) NOT NULL,
    subtitle      VARCHAR2(500),
    cta_text      VARCHAR2(100) NOT NULL,
    target_url    VARCHAR2(255) NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL,
    is_active     NUMBER(10,0) DEFAULT 1 NOT NULL
);

-- 7. SAVINGS EVENTS
CREATE TABLE sep_savings_events (
    id        NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    title     VARCHAR2(255) NOT NULL,
    subtitle  VARCHAR2(500) NOT NULL,
    bg_color  VARCHAR2(30) NOT NULL,
    image_url VARCHAR2(500),
    cta_text  VARCHAR2(100) NOT NULL,
    is_active NUMBER(10,0) DEFAULT 1 NOT NULL
);

-- 8. SAVINGS TIERS
CREATE TABLE sep_savings_tiers (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    event_id      NUMBER(19,0) NOT NULL,
    label         VARCHAR2(100) NOT NULL,
    discount_text VARCHAR2(50) NOT NULL,
    date_range    VARCHAR2(100) NOT NULL,
    badge_color   VARCHAR2(30) NOT NULL,
    text_color    VARCHAR2(30) NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_sep_st_event FOREIGN KEY (event_id) REFERENCES sep_savings_events(id) ON DELETE CASCADE
);

-- 9. PROMO OFFERS
CREATE TABLE sep_promo_offers (
    id                   NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    offer_code           VARCHAR2(150) NOT NULL UNIQUE,
    title                VARCHAR2(255) NOT NULL,
    description_text     VARCHAR2(1000) NOT NULL,
    promo_code           VARCHAR2(50),
    discount_percent     NUMBER(10,0),
    min_order_amount     NUMBER(12,2),
    legal_copy           VARCHAR2(1000) NOT NULL,
    action_label         VARCHAR2(100) NOT NULL,
    details_action_label VARCHAR2(100) NOT NULL,
    image_url            VARCHAR2(500) NOT NULL,
    display_order        NUMBER(10,0) DEFAULT 0 NOT NULL,
    is_active            NUMBER(10,0) DEFAULT 1 NOT NULL
);

-- 10. FEATURE TILES
CREATE TABLE sep_feature_tiles (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    tile_code     VARCHAR2(150) NOT NULL UNIQUE,
    bg_color      VARCHAR2(30) NOT NULL,
    text_color    VARCHAR2(30) NOT NULL,
    title         VARCHAR2(255) NOT NULL,
    subtitle      VARCHAR2(500),
    cta_text      VARCHAR2(100) NOT NULL,
    image_url     VARCHAR2(500) NOT NULL,
    target_url    VARCHAR2(255) NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL
);

-- 11. REWARD ITEMS
CREATE TABLE sep_reward_items (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    reward_code   VARCHAR2(100) NOT NULL UNIQUE,
    brand         VARCHAR2(150) NOT NULL,
    name          VARCHAR2(255) NOT NULL,
    points_label  VARCHAR2(50) NOT NULL,
    points_cost   NUMBER(10,0) DEFAULT 100 NOT NULL,
    image_url     VARCHAR2(500) NOT NULL,
    reward_url    VARCHAR2(500) NOT NULL,
    stock_qty     NUMBER(10,0) DEFAULT 50 NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL,
    is_active     NUMBER(10,0) DEFAULT 1 NOT NULL
);

-- 12. GUIDANCE LINKS
CREATE TABLE sep_guidance_links (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    label         VARCHAR2(100) NOT NULL,
    slug          VARCHAR2(100) NOT NULL UNIQUE,
    icon_color    VARCHAR2(30) NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL
);

-- 13. REASSURANCE BANNERS
CREATE TABLE sep_reassurance_banners (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    banner_code   VARCHAR2(150) NOT NULL UNIQUE,
    bg_color      VARCHAR2(30) NOT NULL,
    title         VARCHAR2(255) NOT NULL,
    subtitle      VARCHAR2(500),
    cta_text      VARCHAR2(100) NOT NULL,
    image_url     VARCHAR2(500) NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL
);

-- 14. FOOTER COLUMNS
CREATE TABLE sep_footer_columns (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    title         VARCHAR2(100) NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL
);

-- 15. FOOTER LINKS
CREATE TABLE sep_footer_links (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    column_id     NUMBER(19,0) NOT NULL,
    label         VARCHAR2(150) NOT NULL,
    href          VARCHAR2(255) NOT NULL,
    display_order NUMBER(10,0) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_sep_flink_col FOREIGN KEY (column_id) REFERENCES sep_footer_columns(id) ON DELETE CASCADE
);

-- 16. STORES
CREATE TABLE sep_stores (
    id             NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name           VARCHAR2(150) NOT NULL,
    address        VARCHAR2(255) NOT NULL,
    city           VARCHAR2(100) NOT NULL,
    state_code     VARCHAR2(50) NOT NULL,
    zip_code       VARCHAR2(20) NOT NULL,
    distance_label VARCHAR2(50) NOT NULL,
    hours_label    VARCHAR2(100) NOT NULL,
    is_active      NUMBER(10,0) DEFAULT 1 NOT NULL
);

-- 17. USER FAVORITES (LOVES)
CREATE TABLE sep_user_favorites (
    id         NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    user_id    NUMBER(19,0) NOT NULL,
    product_id NUMBER(19,0) NOT NULL,
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_sep_user_fav UNIQUE (user_id, product_id),
    CONSTRAINT fk_sep_fav_user FOREIGN KEY (user_id) REFERENCES sep_users(id) ON DELETE CASCADE,
    CONSTRAINT fk_sep_fav_prod FOREIGN KEY (product_id) REFERENCES sep_products(id) ON DELETE CASCADE
);

-- 18. CART ITEMS
CREATE TABLE sep_cart_items (
    id         NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    user_id    NUMBER(19,0) NOT NULL,
    product_id NUMBER(19,0) NOT NULL,
    quantity   NUMBER(10,0) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_sep_cart_item UNIQUE (user_id, product_id),
    CONSTRAINT fk_sep_cart_user FOREIGN KEY (user_id) REFERENCES sep_users(id) ON DELETE CASCADE,
    CONSTRAINT fk_sep_cart_prod FOREIGN KEY (product_id) REFERENCES sep_products(id) ON DELETE CASCADE
);

-- 19. ORDERS
CREATE TABLE sep_orders (
    id                NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    order_code        VARCHAR2(50) NOT NULL UNIQUE,
    user_id           NUMBER(19,0) NOT NULL,
    order_status      VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    subtotal_amount   NUMBER(12,2) NOT NULL,
    discount_amount   NUMBER(12,2) DEFAULT 0.00 NOT NULL,
    total_amount      NUMBER(12,2) NOT NULL,
    promo_code        VARCHAR2(50),
    shipping_name     VARCHAR2(100) NOT NULL,
    shipping_phone    VARCHAR2(20) NOT NULL,
    shipping_address  VARCHAR2(255) NOT NULL,
    fulfillment_store VARCHAR2(150),
    points_earned     NUMBER(10,0) DEFAULT 0 NOT NULL,
    created_at        TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at        TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_sep_order_user FOREIGN KEY (user_id) REFERENCES sep_users(id)
);

CREATE INDEX idx_sep_order_user ON sep_orders(user_id, created_at);

-- 20. ORDER ITEMS
CREATE TABLE sep_order_items (
    id           NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    order_id     NUMBER(19,0) NOT NULL,
    product_id   NUMBER(19,0) NOT NULL,
    sku_id       VARCHAR2(50) NOT NULL,
    product_name VARCHAR2(255) NOT NULL,
    brand        VARCHAR2(150) NOT NULL,
    image_url    VARCHAR2(500) NOT NULL,
    unit_price   NUMBER(12,2) NOT NULL,
    quantity     NUMBER(10,0) NOT NULL,
    line_total   NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_sep_oi_order FOREIGN KEY (order_id) REFERENCES sep_orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_sep_oi_prod FOREIGN KEY (product_id) REFERENCES sep_products(id)
);

-- 21. REWARD REDEMPTIONS
CREATE TABLE sep_reward_redemptions (
    id           NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    user_id      NUMBER(19,0) NOT NULL,
    reward_id    NUMBER(19,0) NOT NULL,
    points_spent NUMBER(10,0) NOT NULL,
    created_at   TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_sep_rr_user FOREIGN KEY (user_id) REFERENCES sep_users(id) ON DELETE CASCADE,
    CONSTRAINT fk_sep_rr_reward FOREIGN KEY (reward_id) REFERENCES sep_reward_items(id)
);

-- 22. SUBSCRIPTIONS (Email & SMS)
CREATE TABLE sep_subscriptions (
    id            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    channel_type  VARCHAR2(20) NOT NULL,
    contact_value VARCHAR2(150) NOT NULL,
    created_at    TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_sep_sub_channel UNIQUE (channel_type, contact_value)
);

-- 23. AI CHAT MESSAGES
CREATE TABLE sep_ai_chat_messages (
    id           NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    session_key  VARCHAR2(100) NOT NULL,
    user_id      NUMBER(19,0),
    sender_type  VARCHAR2(20) NOT NULL,
    message_text VARCHAR2(2000) NOT NULL,
    created_at   TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_sep_chat_sess ON sep_ai_chat_messages(session_key, created_at);

-- 24. AUDIT LOGS
CREATE TABLE sep_audit_logs (
    id             NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    actor_user_id  NUMBER(19,0),
    actor_username VARCHAR2(50) NOT NULL,
    action_type    VARCHAR2(50) NOT NULL,
    target_type    VARCHAR2(50) NOT NULL,
    target_id      VARCHAR2(50),
    detail_text    VARCHAR2(1000),
    created_at     TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_sep_audit_time ON sep_audit_logs(created_at);
